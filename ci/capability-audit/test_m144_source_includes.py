from pathlib import Path
import subprocess
import tempfile
import unittest
from audit_m144_source_includes import audit, references


class SourceIncludeAuditTests(unittest.TestCase):
    def test_records_conditional_context_without_claiming_it_is_active(self):
        result = references('#if BUILDFLAG(DISABLED)\n#include "arkweb/missing.cc"\n#endif\n// #include "arkweb/comment.h"\n')
        self.assertEqual(len(result), 1)
        self.assertEqual(result[0]['line'], 2)
        self.assertEqual(result[0]['preceding_context'], ['#if BUILDFLAG(DISABLED)'])
        spaced = references('\n\n   #include "arkweb/example.h"\n')
        self.assertEqual(spaced[0]['line'], 3)

    def test_present_and_missing_actual_tracked_inputs(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)
            for child in (source, source / 'arkweb', source / 'cef'):
                child.mkdir(parents=True, exist_ok=True)
                subprocess.run(['git', 'init', '-q', str(child)], check=True)
                path = child / 'probe.cc'
                path.write_text('#include "arkweb/present.h"\n#include "arkweb/missing.h"\n')
                subprocess.run(['git', '-C', str(child), 'add', 'probe.cc'], check=True)
                subprocess.run(['git', '-C', str(child), '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid',
                                '-c', 'commit.gpgsign=false', 'commit', '-qm', 'fixture'], check=True)
            (source / 'arkweb/present.h').write_text('// actual input\n')
            result = audit(source)
            self.assertEqual(result['missing_count'], 3)
            self.assertFalse(result['first_artifact_behavior_gate_passed'])
            self.assertTrue(all(item['include'] == 'arkweb/missing.h' for item in result['missing_references']))
            self.assertTrue(all(item['active_feature'].startswith('unknown') for item in result['missing_references']))
            generated = source / 'out/actual/gen'
            (generated / 'arkweb').mkdir(parents=True)
            (generated / 'arkweb/missing.h').write_text('// generated by the actual fixture GN task\n')
            resolved = audit(source, [generated])
            self.assertEqual(resolved['missing_count'], 0)
            self.assertEqual(len(resolved['generated_headers_sha256']), 1)


if __name__ == '__main__':
    unittest.main()
